/**
 * Baby silhouettes — five side profiles, one per developmental stage, drawn in
 * the pose a baby is actually in.
 *
 * Each is a single closed path (head at top) meant to be filled with one accent
 * colour. No faces, no clinical detail: a solid shape that reads as "this is
 * how big your baby is, and this is how they are lying".
 *
 * **Curled-pose scaling.** Every figure is curled, because that is the truth of
 * the womb. The measurement the app quotes is not: from week 20 the official
 * number is crown-to-HEEL with the legs stretched out, which no curled drawing
 * can span. `spanFraction` closes that gap. It is the fraction of the week's
 * official length that the drawn `crownY → lowestY` span represents:
 *
 * ```
 * span = lowestY - crownY;                              // drawn, viewBox units
 * k    = (lengthMm * spanFraction * pxPerMm) / span;     // units → CSS px
 * ```
 *
 * Render the SVG at `viewBox.w × k` by `viewBox.h × k` CSS pixels and the
 * figure occupies exactly the space the curled baby occupies. Weeks 4–19 are
 * reported crown-rump, measured on this very curl, so their `spanFraction` is
 * ~1.0. Weeks 20+ are reported crown-heel stretched, and a curled fetus really
 * does occupy about 0.66–0.71 of its stretched length — hence the smaller
 * fractions there. "Actual size" stays true either way: the drawing is the room
 * the baby takes up, and the stretched head-to-heel figure remains the stat.
 *
 * (The old contract forced legs-extended poses from week 20 so `crown → heel`
 * could span the whole drawing. It made the babies look like standing toddlers.
 * `spanFraction` buys the honest pose back without inflating the render.)
 */

